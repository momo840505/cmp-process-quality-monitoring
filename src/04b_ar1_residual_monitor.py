"""Step 04B — AR(1) residual monitoring DIAGNOSTIC (not production SPC).

Uses only 04A TRAINING Stage-A chart points. Fits each group's AR(1) to
reference 60% rows; freezes coefficient and descriptive reference residual
limits for the later 40%. Does not read test or validation outcomes.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

GROUPS = ("Codes 1-3", "Codes 4-6")
NEEDED = {
    "code_group", "WAFER_ID", "order_within_group", "zone", "first_timestamp",
    "AVG_REMOVAL_RATE", "outside_provisional_3sigma", "reference_CL_provisional",
    "reference_UCL_provisional", "reference_LCL_provisional",
}


def lag1(values: np.ndarray) -> float:
    """Diagnostic Pearson correlation of adjacent values (not a p-value)."""
    z = np.asarray(values, dtype=float)
    if len(z) < 3 or np.std(z[:-1]) == 0 or np.std(z[1:]) == 0:
        return float("nan")
    return float(np.corrcoef(z[:-1], z[1:])[0, 1])


def run(input_csv: Path, out_dir: Path) -> None:
    if not input_csv.is_file():
        raise FileNotFoundError(f"Missing Step 04A output: {input_csv}")
    df = pd.read_csv(input_csv)
    missing = NEEDED - set(df.columns)
    if missing:
        raise ValueError(f"Step 04A file lacks columns: {sorted(missing)}")
    if df["code_group"].isna().any() or set(df["code_group"]) != set(GROUPS):
        raise ValueError("Unexpected code groups; expected exactly Codes 1-3 and Codes 4-6.")
    if df[list(NEEDED - {"code_group", "zone"})].isna().any().any():
        raise ValueError("Required values are missing.")
    if len(df) != 1161 or df.duplicated(["code_group", "WAFER_ID"]).any():
        raise ValueError("Expected exactly 1,161 unique Step 04A chart points.")

    out_dir.mkdir(parents=True, exist_ok=True)
    figure_dir = out_dir / "figures"
    figure_dir.mkdir(parents=True, exist_ok=True)
    summary_rows, point_dfs, alert_rows = [], [], []

    for group in GROUPS:
        g = df.loc[df["code_group"] == group].sort_values("order_within_group").copy()
        g = g.reset_index(drop=True)
        y = g["AVG_REMOVAL_RATE"].to_numpy(float)
        orders = g["order_within_group"].to_numpy(int)
        if not np.array_equal(orders, np.arange(1, len(g) + 1)):
            raise ValueError(f"Non-consecutive ordering in {group}")
        if np.any(np.diff(g["first_timestamp"].to_numpy(float)) < 0):
            raise ValueError(f"Non-monotone timestamp in {group}")
        ref = g["zone"].eq("reference").to_numpy()
        if ref.sum() != int(len(g) * 0.60) and ref.sum() != round(len(g) * 0.60):
            # Explicitly allow the reference size generated by 04A using int truncation.
            raise ValueError(f"Unexpected 60% split in {group}")
        n_ref = int(ref.sum())
        if not (ref[:n_ref].all() and (~ref[n_ref:]).all()):
            raise ValueError(f"Reference rows must precede later rows in {group}")
        if n_ref <= 30:
            raise ValueError("Too few reference observations")
        if g["outside_provisional_3sigma"].dtype != bool:
            raise ValueError("Expected Boolean 04A 3sigma flags")

        # OLS AR(1) fit ONLY on adjacent values both in the first 60%.
        x_ref, target_ref = y[:n_ref - 1], y[1:n_ref]
        var_x = np.var(x_ref, ddof=1)
        if var_x == 0:
            raise ValueError("Constant AR(1) predictor cannot be fit")
        phi = float(np.cov(x_ref, target_ref, ddof=1)[0, 1] / var_x)
        intercept = float(target_ref.mean() - phi * x_ref.mean())

        pred = np.full(len(y), np.nan)
        pred[1:] = intercept + phi * y[:-1]
        residual = y - pred
        reference_residual = residual[1:n_ref]
        center = float(np.mean(reference_residual))
        sigma = float(np.std(reference_residual, ddof=1))
        if not np.isfinite(sigma) or sigma <= 0:
            raise ValueError(f"Nonpositive residual standard deviation for {group}")
        lcl, ucl = center - 3 * sigma, center + 3 * sigma
        outside = (residual < lcl) | (residual > ucl)
        outside[0] = False  # First point has no lagged observation.

        # Compare COUNTS, not accuracy: there is no true failure ground truth.
        raw_i = g["outside_provisional_3sigma"].to_numpy(bool)
        ar_reference_count = int(outside[1:n_ref].sum())
        ar_monitor_count = int(outside[n_ref:].sum())
        i_reference_count = int(raw_i[:n_ref].sum())
        i_monitor_count = int(raw_i[n_ref:].sum())
        n_later = len(g) - n_ref

        detail = g[["code_group", "WAFER_ID", "order_within_group", "zone", "first_timestamp", "AVG_REMOVAL_RATE"]].copy()
        detail["ar1_fitted_intercept_reference_only"] = intercept
        detail["ar1_fitted_phi_reference_only"] = phi
        detail["predicted_MRR_from_previous_observed_MRR"] = pred
        detail["ar1_residual"] = residual
        detail["reference_residual_center"] = center
        detail["provisional_residual_LCL"] = lcl
        detail["provisional_residual_UCL"] = ucl
        detail["provisional_AR1_residual_flag"] = outside
        detail["step04a_provisional_I_chart_flag"] = raw_i
        point_dfs.append(detail)
        alert_rows.append(detail.loc[(outside | raw_i) & (detail["zone"] == "monitor")].copy())

        summary_rows.append({
            "code_group": group,
            "reference_n": n_ref,
            "reference_residual_n": n_ref - 1,
            "monitor_n": n_later,
            "reference_MRR_mean": float(y[:n_ref].mean()),
            "monitor_MRR_mean": float(y[n_ref:].mean()),
            "reference_raw_MRR_lag1": lag1(y[:n_ref]),
            "reference_residual_lag1": lag1(reference_residual),
            "monitor_residual_lag1": lag1(residual[n_ref:]),
            "ar1_intercept": intercept,
            "ar1_phi": phi,
            "reference_residual_SD_in_sample": sigma,
            "provisional_residual_LCL": lcl,
            "provisional_residual_UCL": ucl,
            "I_chart_reference_flags": i_reference_count,
            "AR1_reference_flags": ar_reference_count,
            "I_chart_monitor_flags": i_monitor_count,
            "AR1_monitor_flags": ar_monitor_count,
            "I_chart_monitor_fraction": i_monitor_count / n_later,
            "AR1_monitor_fraction": ar_monitor_count / n_later,
            "both_monitor_flags": int((outside[n_ref:] & raw_i[n_ref:]).sum()),
        })

        fig, ax = plt.subplots(figsize=(13, 5.5))
        j = np.arange(1, len(y) + 1)
        ax.scatter(j[1:n_ref], residual[1:n_ref], s=17, alpha=.65, label="Reference residuals (TRAIN first 60%)")
        ax.scatter(j[n_ref:], residual[n_ref:], s=17, alpha=.65, label="Later residuals (TRAIN last 40%)")
        bad = np.flatnonzero(outside)
        ax.scatter(j[bad], residual[bad], marker="x", s=70, linewidths=1.8, label=f"Outside illustrative residual limits: {len(bad)}")
        ax.axhline(center, color="black", label="Reference residual center (NOT qualified CL)")
        ax.axhline(ucl, color="tab:red", ls="--", label=f"Reference-only residual +/-3 SD: {ucl:.2f} / {lcl:.2f}")
        ax.axhline(lcl, color="tab:red", ls="--")
        ax.axvline(n_ref + .5, color="tab:green", ls=":", label="Reference/later split")
        ax.set_title(f"Stage A / {group} — AR(1) one-step residuals (exploratory, NOT qualified SPC)")
        ax.set_xlabel("Order by first sensor timestamp (NOT validated fab production order)")
        ax.set_ylabel("Observed MRR minus AR(1) predicted MRR (dataset scale)")
        ax.grid(alpha=.2)
        ax.legend(loc="upper left", fontsize=8)
        fig.text(.5, .015, "In-sample reference fit; no verified stable baseline or true defect labels. Fewer alerts do NOT imply better detection.",ha="center",fontsize=9)
        fig.tight_layout(rect=(0,.05,1,1))
        tag = "codes_1_3" if group == "Codes 1-3" else "codes_4_6"
        fig.savefig(figure_dir / f"04b_{tag}_AR1_residual_chart.png", dpi=145)
        plt.close(fig)

    s = pd.DataFrame(summary_rows)
    allpoints = pd.concat(point_dfs, ignore_index=True)
    alarms = pd.concat(alert_rows, ignore_index=True)
    assert len(allpoints) == len(df) == 1161
    assert s.reference_n.sum() == 218 + 478
    assert s.monitor_n.sum() == 146 + 319
    assert s.I_chart_monitor_flags.sum() == 31 + 113
    assert s.I_chart_reference_flags.sum() == 10 + 178

    s.to_csv(out_dir / "04b_reference_only_AR1_summary.csv", index=False)
    allpoints.to_csv(out_dir / "04b_all_AR1_residual_points.csv", index=False)
    alarms.to_csv(out_dir / "04b_later_any_method_flags.csv", index=False)
    notes = {
        "scope": "Only Step04A TRAINING Stage A 1,161 included chart rows; no Test/Validation data.",
        "purpose": "Compare preliminary conventional I-chart flags against preliminary AR(1) one-step residual flags. Not an approved SPC system.",
        "model": "Fit OLS MRR[t] = intercept + phi * MRR[t-1] + residual[t] ONLY on first 60% consecutive training values within each code group. Freeze model for later 40%.",
        "residual_limits": "In-sample reference residual mean +/- 3 times reference residual sample SD; NOT validated control limits or known false-alarm rates.",
        "initial_residual": "First observation in each code group has no previous MRR, so its residual is NaN and it is not eligible for AR1 alert.",
        "limitations": [
            "MRR is a post-process quality measurement, so the AR1 monitor can only be evaluated once the current MRR is available. It is not real-time tool-sensor FDC.",
            "The recorded sequence was sorted by first sensor timestamp, not verified fab run chronology; intervals may overlap.",
            "The first 60% is not shown to be a stable Phase-I reference. Reference fit and residual SD are estimated in-sample, potentially optimistic.",
            "Reference residuals may remain serially correlated; this simple AR1 is a diagnostic model, not an approved prewhitening method.",
            "AR1 can adapt to persistent level shifts, thereby missing sustained process changes. A lower flag count does NOT prove higher accuracy.",
            "Four MRR>1000 review records and one noncanonical code signature were excluded by Step04A and retained in its review file; their status remains unverified.",
            "No failure/defect ground truth, engineering specs, verified stable reference, or validated control limits; no Cp/Cpk or false-positive rates.",
            "Do not use the monitor section for choosing/adjusting coefficients or thresholds; treat this as exploratory and report both methods honestly.",
        ],
    }
    (out_dir / "04b_method_limits.json").write_text(json.dumps(notes, indent=2, ensure_ascii=False), encoding="utf-8")
    print("PASS: Step04A data verified, only TRAINING 1,161 chart points used; no Test/Validation")
    for r in summary_rows:
        print(f"{r['code_group']}: phi={r['ar1_phi']:.3f} | reference residual lag1={r['reference_residual_lag1']:.3f} | "
              f"later flags: I-chart={r['I_chart_monitor_flags']}/{r['monitor_n']}, "
              f"AR1 residual={r['AR1_monitor_flags']}/{r['monitor_n']}")
    print(f"Saved 4 reports and 2 figures to {out_dir}")
    print("Exploratory comparison ONLY; fewer AR1 flags do not establish better detection, stable process, or approved SPC limits.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=Path("outputs/analysis/04a_training_chart_points.csv"))
    parser.add_argument("--output", type=Path, default=Path("outputs/analysis"))
    a = parser.parse_args()
    run(a.input, a.output)


if __name__ == "__main__":
    main()
